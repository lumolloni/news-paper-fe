import { defineConfig, loadEnv, type Plugin } from 'vite'
import vue from '@vitejs/plugin-vue'
import { VitePWA } from 'vite-plugin-pwa'
import { fileURLToPath, URL } from 'node:url'

/**
 * Emit robots.txt at build time. The `Sitemap:` directive must be an absolute
 * URL, so it is derived from VITE_SITE_URL (omitted when that is unset).
 */
function robotsTxt(siteUrl: string): Plugin {
  return {
    name: 'robots-txt',
    apply: 'build',
    generateBundle() {
      const lines = [
        'User-agent: *',
        'Allow: /',
        '',
        '# Keep private / non-content routes out of the index.',
        'Disallow: /login',
        'Disallow: /register',
        'Disallow: /live',
        'Disallow: /search',
      ]
      if (siteUrl) lines.push('', `Sitemap: ${siteUrl.replace(/\/$/, '')}/sitemap.xml`)
      this.emitFile({ type: 'asset', fileName: 'robots.txt', source: lines.join('\n') + '\n' })
    },
  }
}

export default defineConfig(({ mode }) => ({
  plugins: [
    robotsTxt(loadEnv(mode, process.cwd(), '').VITE_SITE_URL ?? ''),
    // Vidstack ships web components (<media-player>, <media-provider>, …).
    // Tell the Vue compiler to leave `media-*` tags as custom elements.
    vue({ template: { compilerOptions: { isCustomElement: (tag) => tag.startsWith('media-') } } }),
    VitePWA({
      registerType: 'autoUpdate',
      // Load registerSW.js with `defer` so it doesn't block first paint.
      injectRegister: 'script-defer',
      includeAssets: ['favicon.svg'],
      manifest: {
        name: 'Meridian — Modern News',
        short_name: 'Meridian',
        description: 'A modern editorial news portal.',
        theme_color: '#0f0f0f',
        background_color: '#ffffff',
        display: 'standalone',
        start_url: '/',
        icons: [
          { src: 'pwa-192.png', sizes: '192x192', type: 'image/png' },
          { src: 'pwa-512.png', sizes: '512x512', type: 'image/png' },
          { src: 'pwa-512.png', sizes: '512x512', type: 'image/png', purpose: 'maskable' },
        ],
      },
      workbox: {
        navigateFallbackDenylist: [/^\/api/, /^\/admin/],
        runtimeCaching: [
          {
            urlPattern: ({ url }) => url.pathname.startsWith('/api'),
            handler: 'NetworkFirst',
            options: {
              cacheName: 'strapi-api',
              expiration: { maxEntries: 200, maxAgeSeconds: 60 * 60 * 24 },
              cacheableResponse: { statuses: [0, 200] },
            },
          },
          {
            urlPattern: ({ request }) => request.destination === 'image',
            handler: 'CacheFirst',
            options: {
              cacheName: 'images',
              expiration: { maxEntries: 300, maxAgeSeconds: 60 * 60 * 24 * 30 },
              cacheableResponse: { statuses: [0, 200] },
            },
          },
        ],
      },
    }),
  ],
  resolve: {
    alias: {
      '@': fileURLToPath(new URL('./src', import.meta.url)),
    },
  },
  // es2022 enables top-level await (used in main.ts and by Vidstack internally).
  build: { target: 'es2022' },
  // Vidstack ships native custom-element classes that break when Vite pre-bundles
  // them ("Class extends value undefined"); exclude it from dep optimization.
  optimizeDeps: { exclude: ['vidstack'], esbuildOptions: { target: 'es2022' } },
  server: {
    port: 5173,
    proxy: {
      '/api': { target: 'http://localhost:1337', changeOrigin: true },
      '/uploads': { target: 'http://localhost:1337', changeOrigin: true },
      // Socket.IO real-time channel (new-article toasts). ws:true upgrades the
      // connection so the WebSocket transport works through the dev proxy.
      '/socket.io': { target: 'http://localhost:1337', changeOrigin: true, ws: true },
      // Dynamic sitemap is generated by Strapi (content-API route under /api).
      '/sitemap.xml': {
        target: 'http://localhost:1337',
        changeOrigin: true,
        rewrite: () => '/api/sitemap.xml',
      },
    },
  },
}))
